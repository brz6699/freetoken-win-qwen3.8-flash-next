def check(name, cond, detail=""):
    print(f"[{'PASS' if cond else 'FAIL'}] {name} {detail}")
    if not cond:
        FAIL.append(name)


def make_group():
    return LinearGatedDeltaGroupConfig(
        name="g", layer_ids=(0,), num_key_heads=1, num_value_heads=1,
        key_head_dim=4, value_head_dim=4, conv_kernel_dim=2, output_gate="silu",
    )


class World:
    """One pool + page table + CacheManager, and the token universe for fingerprints."""

    def __init__(self, ids_all):
        self.ids_all = ids_all  # prompt + generated, all distinct (fingerprint universe)
        self.pool = LinearStatePool(make_group(), num_slots=8, dtype=torch.float32,
                                    device=torch.device("cpu"), tp_size=1)
        self.n_pages = 512
        self.page_table = torch.zeros(32, self.n_pages, dtype=torch.int32)
        self.cm = CacheManager(self.n_pages, 1, self.page_table, "hybrid_radix",
                               linear_state_pool=self.pool)
        self.pc = self.cm.prefix_cache

    def fp(self, slot):
        return float(self.pool.conv_states[0, slot, 0, 0])

    def advance(self, slot, n):
        # state after n tokens = fingerprint of the first n tokens
        self.pool.conv_states[0, slot, 0, 0] = float(sum(self.ids_all[:n]))

    def pages_conserved(self):
        tree_tokens = self.pc.full_evictable + self.pc.full_protected
        return len(self.cm.free_slots) + tree_tokens == self.n_pages, (
            f"free={len(self.cm.free_slots)} tree={tree_tokens} total={self.n_pages}")


