"""P4 finish-time key regression: the content key must reach req.cached_len.

At finish, cached_len = prompt + generated - 1 and the GDN live slot holds the state
after cached_len tokens. If the mm key stops at the prompt end (the old bug), the hybrid
insert truncates the node boundary to the key length: the donated state over-advances the
boundary (a multi-turn continuation would COW-restore a state that already contains the
previous turn's generated tokens) and the generated KV pages are orphaned (leak).

This test drives the REAL CacheManager(hybrid_radix) + REAL LinearStatePool through a
full two-turn lifecycle, mirroring the engine's exact accounting: the forward's
complete_one() sets cached_len = device_len, the scheduler then appends the sampled token
(numel == device_len), and the finishing token is never paged (its KV forward never runs).
GDN state is simulated by a prefix fingerprint on pool.conv_states[0, slot, 0, 0]: the
state "after N tokens" carries sum(ids_all[:N]) (all ids distinct -> prefix sums unique),
which is exactly the invariant the node boundary must honor.

  python -X utf8 verification/p4_finish_key_test.py
"""

